export function renderPrContext({ base, head, paths, navigators, status }) {
  const uniqueNavigators = [...new Set(navigators)].sort();
  const lines = [
    `<!-- CHARTHOUSE:START head=${head || "working-tree"} -->`,
    "## Charthouse context",
    "",
    `- Comparison base: ${base || "working tree"}`,
    `- Changed paths: ${paths.length}`,
    `- Primary Navigators: ${uniqueNavigators.length ? uniqueNavigators.join(", ") : "No Navigator matched"}`,
    `- Bearing status: ${status}`,
    "",
    "### Affected paths",
    "",
    ...(paths.length ? paths.slice(0, 20).map((path) => `- \`${path}\``) : ["- Charthouse found no changed paths."]),
    "",
    "### Required author context",
    "",
    "State the reason for the change, the Charter constraints, the verified",
    "knowledge, the architecture effect, and unresolved risks.",
    "",
    "<!-- CHARTHOUSE:END -->"
  ];
  return `${lines.join("\n")}\n`;
}

